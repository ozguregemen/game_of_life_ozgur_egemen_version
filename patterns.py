def save_pattern(pattern, name, description=""):
    """Save a custom pattern to a JSON file"""
    if not os.path.exists("patterns"):
        os.makedirs("patterns")
    
    pattern_data = {
        "name": name,
        "description": description,
        "pattern": pattern,
        "date_created": str(datetime.datetime.now())
    }
    
    filename = f"patterns/{name.lower().replace(' ', '_')}.json"
    with open(filename, 'w') as f:
        json.dump(pattern_data, f)

def delete_pattern(name):
    """Delete a custom pattern"""
    filename = f"patterns/{name.lower().replace(' ', '_')}.json"
    try:
        os.remove(filename)
        return True
    except FileNotFoundError:
        return False

def load_pattern(name):
    """Load a pattern from a JSON file"""
    filename = f"patterns/{name.lower().replace(' ', '_')}.json"
    try:
        with open(filename, 'r') as f:
            return json.load(f)
    except FileNotFoundError:
        return None

def get_all_patterns():
    """Get all available patterns (built-in and custom)"""
    all_patterns = PATTERNS.copy()
    
    # Load custom patterns
    if os.path.exists("patterns"):
        for filename in os.listdir("patterns"):
            if filename.endswith(".json"):
                with open(os.path.join("patterns", filename), 'r') as f:
                    pattern_data = json.load(f)
                    all_patterns[pattern_data["name"].lower()] = pattern_data
    
    return all_patterns

def rotate_pattern(pattern, degrees=90):
    """Rotate a pattern by the specified degrees (90, 180, or 270)"""
    if degrees not in [90, 180, 270]:
        raise ValueError("Rotation must be 90, 180, or 270 degrees")
    
    # Convert to list of lists if it's not already
    pattern = [list(row) for row in pattern]
    
    # Rotate 90 degrees clockwise
    if degrees == 90:
        return list(zip(*pattern[::-1]))
    # Rotate 180 degrees
    elif degrees == 180:
        return [row[::-1] for row in pattern[::-1]]
    # Rotate 270 degrees clockwise
    else:  # 270
        return list(zip(*pattern))[::-1]

def flip_pattern(pattern, horizontal=True):
    """Flip a pattern horizontally or vertically"""
    if horizontal:
        return [row[::-1] for row in pattern]
    else:
        return pattern[::-1] 